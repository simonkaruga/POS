#!/usr/bin/env node
/**
 * Generates every platform's token file from design/tokens.json.
 *   node design/build-tokens.mjs          write the files
 *   node design/build-tokens.mjs --check  fail if a file is out of date (CI / unit test)
 *
 * Web reads tokens.json directly in tailwind.config.js and gets its CSS variables from tokens.css.
 * The mobile apps are outside the npm workspace, so each gets a generated constants/tokens.ts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(fs.readFileSync(path.join(root, 'design/tokens.json'), 'utf8'));
const check = process.argv.includes('--check');
const HEADER = 'GENERATED by design/build-tokens.mjs from design/tokens.json. Do not edit by hand.';

const strip = ({ _comment, ...rest }) => rest;
const rgb = (hex) => { const h = hex.replace('#', ''); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' '); };

function webCss() {
  const light = {
    'c-white': '#FFFFFF', 'c-gray-50': t.neutral[50], 'c-gray-100': t.neutral[100], 'c-gray-200': t.neutral[200], 'c-gray-300': t.neutral[300],
    'c-text-900': t.neutral[900], 'c-text-800': t.neutral[800], 'c-text-700': t.neutral[700], 'c-text-600': t.neutral[600], 'c-text-500': t.neutral[500], 'c-text-400': t.neutral[500],
    'c-page': t.neutral[100],
  };
  const dark = {
    'c-white': t.darkSurface.white, 'c-gray-50': t.darkSurface.gray50, 'c-gray-100': t.darkSurface.gray100, 'c-gray-200': t.darkSurface.gray200, 'c-gray-300': t.darkSurface.gray300,
    'c-text-900': t.darkText.gray900, 'c-text-800': t.darkText.gray800, 'c-text-700': t.darkText.gray700, 'c-text-600': t.darkText.gray600, 'c-text-500': t.darkText.gray500, 'c-text-400': t.darkText.gray400,
    'c-page': t.neutral[950],
  };
  const block = (sel, vars) => `${sel} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${rgb(v)};`).join('\n')}\n}\n`;
  return `/* ${HEADER} */\n${block(':root', light)}${block('.dark', dark)}`;
}

function mobileTs() {
  const obj = (o) => JSON.stringify(o, null, 2).replace(/"([A-Za-z_][A-Za-z0-9_]*)":/g, '$1:').replace(/"/g, "'");
  return `// ${HEADER}
export const Brand = ${obj(t.brand)} as const;

export const Neutral = ${obj(t.neutral)} as const;

export const Status = ${obj(t.status)} as const;

/** Faida Navy (the logo wordmark) and Faida Orange (the logo stroke, an accent: use Accent.text for orange text). */
export const Navy = ${obj(strip(t.navy))} as const;
export const Accent = ${obj(strip(t.accent))} as const;

/** Radii, spacing and type sizes in density-independent pixels. */
export const Radius = ${obj(t.radius)} as const;
export const Space = ${obj(t.space)} as const;
export const FontSize = ${obj(t.fontSize)} as const;

/** The smallest a thing you tap may be (WCAG 2.5.5 / platform guidance). */
export const TOUCH_TARGET = ${t.touchTarget};

/** The colours every Faida app starts from. An app's constants/theme.ts builds its own Colors from these. */
export const BaseColors = {
  primary: Brand[600],
  primaryLight: Brand[400],
  primaryDark: Brand[700],
  primarySoft: Brand[100],
  success: Status.success,
  warning: Status.warning,
  error: Status.danger,
  info: Brand[600],
  text: Neutral[900],
  textSecondary: Neutral[500],
  background: Neutral[100],
  card: '#FFFFFF',
  border: Neutral[200],
} as const;
`;
}

/**
 * The light, Cloud-and-blue palette for the two apps that are not Tailwind: the admin console (inline styles)
 * and the landing site (plain CSS). One semantic vocabulary, built from the same tokens as the web app.
 * Blue, purple, cyan and indigo all collapse onto the brand scale (a module does not get its own accent);
 * green, amber and red keep their status meaning and use the text-safe shades.
 */
function semantic() {
  const b = t.brand, n = t.neutral;
  return {
    bg: n[100], surface: n[50], card: '#FFFFFF', cardBorder: n[200], cardBorder2: n[300],
    border: n[200], text: n[900], textSecondary: n[600], textMuted: n[500],
    input: '#FFFFFF', inputBorder: n[300],
    sidebar: '#FFFFFF', sidebarBorder: n[200],
    accent: b[600], accentDark: b[700], accentText: t.brandText.light, accentSoft: b[100], accentTint: b[50],
    blue: t.brandText.light, blue2: t.brandText.light, purple: b[700], cyan: b[400], indigo: b[800],
    green: t.statusText.green, amber: t.statusText.amber, red: t.statusText.red,
    success: t.status.success, warning: t.status.warning, danger: t.status.danger,
    successSoft: t.status.successSoft, warningSoft: t.status.warningSoft, dangerSoft: t.status.dangerSoft,
    overlay: n[950],
  };
}

function adminTs() {
  return `// ${HEADER}
/** Admin console colours: Faida Blue on Cloud. Append two hex digits for transparency, e.g. \`\${C.blue}1f\`. */
export const C = ${JSON.stringify(semantic(), null, 2).replace(/"([A-Za-z0-9_]+)":/g, '$1:').replace(/"/g, "'")} as const;
`;
}

/** CSS variables for the apps that style with plain CSS (the landing site, and the admin console's global rules). */
function landingCss() {
  // Text on the landing pages uses var(--cyan) as a readable accent, so it takes the text-safe brand shade there.
  const s = { ...semantic(), cyan: t.brandText.light };
  const kebab = (k) => k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
  return `/* ${HEADER} */\n:root {\n${Object.entries(s).map(([k, v]) => `  --${kebab(k)}: ${v};`).join('\n')}\n  --brand-50: ${t.brand[50]};\n  --brand-100: ${t.brand[100]};\n  --brand-200: ${t.brand[200]};\n  --brand-300: ${t.brand[300]};\n  --brand-400: ${t.brand[400]};\n  --brand-500: ${t.brand[500]};\n  --brand-600: ${t.brand[600]};\n  --brand-700: ${t.brand[700]};\n  --brand-800: ${t.brand[800]};\n  --brand-900: ${t.brand[900]};\n  --brand-950: ${t.brand[950]};\n  --navy: ${t.navy.DEFAULT};\n  --navy-strong: ${t.navy.strong};\n  --orange: ${t.accent.DEFAULT};\n  --orange-soft: ${t.accent.soft};\n  --orange-text: ${t.accent.text};\n  --bg2: ${s.card};\n  --bg3: ${s.surface};\n  --bg4: ${s.bg};\n  --border2: ${s.cardBorder2};\n  --text2: ${s.textSecondary};\n  --text3: ${s.textMuted};\n  --blue-glow: ${t.brand[600]}47;\n  --blue-dim: ${t.brand[600]}1a;\n  --radius: ${t.radius.lg}px;\n  --radius-lg: ${t.radius.xl}px;\n  --radius-sm: ${t.radius.sm}px;\n  --radius-md: ${t.radius.md}px;\n  --radius-xl: ${t.radius.xl}px;\n}\n`;
}

const targets = [
  ['apps/admin/src/generated/tokens.ts', adminTs()],
  ['apps/landing/tokens.css', landingCss()],
  ['apps/admin/src/generated/tokens.css', landingCss()],
  ['docs/templates/manual-tokens.css', landingCss()],
  ['apps/web/src/styles/tokens.css', webCss()],
  ...['mobile-pos', 'mobile-customer', 'mobile-driver', 'mobile-agent'].map((a) => [`apps/${a}/constants/tokens.ts`, mobileTs()]),
];

let stale = 0;
for (const [rel, content] of targets) {
  const file = path.join(root, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === content) continue;
  if (check) { console.error(`out of date: ${rel}`); stale++; continue; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log(`wrote ${rel}`);
}
if (check && stale) { console.error('Run: npm run tokens'); process.exit(1); }
if (check) console.log('design tokens are up to date');
